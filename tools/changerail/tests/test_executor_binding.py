@pytest.mark.parametrize(
    "case", ["tracked", "unknown", "source", "verification", "history"]
)
def test_unsafe_project_states_are_refused(full_release, case):
    project, engine, _ = full_release
    if case == "tracked":
        put(project, ".changerail/chrl", "tracked")
        git(project, "add", "-f", ".changerail/chrl")
    elif case == "unknown":
        put(
            project,
            ".changerail/chrl",
            "#!/bin/sh\n# Generated by ChangeRail executor-binding v1.\n",
            0o755,
        )
    elif case == "source":
        put(project, ".changerail/source-link.json", "{}")
    elif case == "verification":
        put(
            project,
            ".runtime/changerail/runs/old/verification-attempts/a.json",
            '{"state":"started"}',
        )
    else:
        value = binding.prepare(project, engine)
        put(project, ".runtime/changerail/runs/old/review-budget.json", '{"used":2}')
        with pytest.raises(ValueError, match="history changed"):
            binding.apply(Path(value["proposal"]))
        return
    with pytest.raises(ValueError):
        binding.prepare(project, engine)
    assert not (project / release.BINDING).exists()


@pytest.mark.parametrize("boundary", ["launcher", "binding", "applied"])
def test_crash_reconciles_only_exact_intent_without_resetting_old_runs(
    full_release, monkeypatch, boundary
):
    project, engine, _ = full_release
    run = put(
        project,
        ".runtime/changerail/runs/unfinished/run.json",
        '{"execution_contract":"changerail.native.v1","mode":"delivery","lifecycle_mode":"openspec-v1","finished_at":null,"reviews_used":2,"process_identity":{"engine/identity":"old"}}',
    )
    original = run.read_bytes()
    value = binding.prepare(project, engine)
    path = Path(value["proposal"])
    replace, append = binding._replace, binding._append

    def interrupted_replace(project, name, state):
        replace(project, name, state)
        if (boundary == "launcher" and name == ".changerail/chrl") or (
            boundary == "binding" and name == release.BINDING
        ):
            raise OSError("fixture crash")

    def interrupted_append(path, value):
        if boundary == "applied" and path.name == "applied.json":
            raise OSError("fixture crash")
        append(path, value)

    monkeypatch.setattr(binding, "_replace", interrupted_replace)
    monkeypatch.setattr(binding, "_append", interrupted_append)
    with pytest.raises(OSError, match="fixture crash"):
        binding.apply(path)
    with pytest.raises(ValueError, match="pending"):
        binding.ensure_no_pending(project)
    import subprocess

    blocked = subprocess.run(
        [str(project / ".changerail/chrl"), "--engine-root"],
        capture_output=True,
        text=True,
    )
    assert blocked.returncode == 2
    assert "pending executor binding" in blocked.stderr
    monkeypatch.setattr(binding, "_replace", replace)
    monkeypatch.setattr(binding, "_append", append)
    assert binding.apply(path, reconcile=True)["state"] == "applied"
    assert (path.parent / "reconciled.json").exists()
    assert run.read_bytes() == original
    monkeypatch.setattr(d, "REPO_ROOT", project)
    monkeypatch.setattr(d, "RUNTIME_ROOT", project / ".runtime/changerail")
    monkeypatch.setattr(
        d, "execution_identity", lambda: {"engine/identity": value["identity"]}
    )
    with pytest.raises(d.DeliveryError, match="frozen execution process changed"):
        d.require_frozen_execution(run.parent)


def test_project_and_binding_lock_order_excludes_concurrent_writers(full_release):
    project, engine, _ = full_release
    for name in (
        ".runtime/changerail/delivery.lock",
        ".changerail/.engine-binding.lock",
    ):
        path = put(project, name, "")
        with path.open("r+") as stream:
            fcntl.flock(stream.fileno(), fcntl.LOCK_EX | fcntl.LOCK_NB)
            with pytest.raises(ValueError, match="holds|writer"):
                binding.prepare(project, engine)
        assert not (project / release.BINDING).exists()


def test_live_session_blocks_binding_before_apply(full_release):
    import os
    import subprocess

    project, engine, _ = full_release
    proposal = binding.prepare(project, engine)
    child = subprocess.Popen(
        ["/usr/bin/python3", "-I", "-S", "-c", "print('ready',flush=True);input()"],
        env={
            **os.environ,
            "CHRL_RUN_DIR": str(project / ".runtime/changerail/runs/live"),
        },
        stdin=subprocess.PIPE,
        stdout=subprocess.PIPE,
        text=True,
    )
    try:
        assert child.stdout.readline().strip() == "ready"
        with pytest.raises(ValueError, match="live process"):
            binding.apply(Path(proposal["proposal"]))
        assert not (project / release.BINDING).exists()
    finally:
        child.communicate("done\n", timeout=10)


