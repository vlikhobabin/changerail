def test_initial_preview_apply_idempotence_and_exact_history(full_release):
    project, engine, _ = full_release
    run = put(
        project,
        ".runtime/changerail/runs/old/run.json",
        '{"finished_at":"2026-01-01T00:00:00Z","reviews_used":2,"remaining_budget":17}\n',
    )
    counter = put(
        project,
        ".runtime/changerail/runs/old/review-budget.json",
        '{"used":2,"repair_remaining":17}\n',
    )
    original = {p: p.read_bytes() for p in (run, counter)}
    preview = binding.prepare(project, engine, dry_run=True)
    assert not Path(preview["proposal"]).exists()
    assert not (project / release.BINDING).exists()
    proposal = binding.prepare(project, engine)
    path = Path(proposal["proposal"])
    assert path == Path(preview["proposal"])
    assert binding.apply(path, dry_run=True)["state"] == "preview"
    first = binding.apply(path)
    assert binding.apply(path) == first
    assert {p: p.read_bytes() for p in original} == original
    assert list((project / ".runtime/changerail/runs").iterdir()) == [run.parent]
    assert (path.parent / "intent.json").is_file()
    assert (path.parent / "applied.json").is_file()


def test_snapshot_migration_requires_existing_exact_identity_and_retains_old_bytes(
    full_release, tmp_path
):
    project, engine, _ = full_release
    sealed = tmp_path / "snapshot"
    snapshot.create_snapshot(engine, sealed)
    previous = snapshot.bind_engine(project, sealed)
    original = (project / release.BINDING).read_bytes()
    for identity in (None, "wrong"):
        with pytest.raises(ValueError, match="previous.identity|previous identity"):
            binding.prepare(project, engine, previous_identity=identity)
    value = binding.prepare(
        project, engine, previous_identity=previous["engine_identity"]
    )
    assert bytes.fromhex(value["before"][release.BINDING]["bytes"]) == original
    binding.apply(Path(value["proposal"]))
    assert (
        release.document(project / release.BINDING)["schema"] == release.BINDING_SCHEMA
    )
    with pytest.raises(
        snapshot.EngineSnapshotError, match="invalid project engine binding"
    ):
        snapshot.verify_binding(project)
    # Returning to the snapshot is another explicit transaction, not file restore.
    back = binding.prepare(
        project, sealed, kind="snapshot", previous_identity=value["identity"]
    )
    binding.apply(Path(back["proposal"]))
    assert snapshot.verify_binding(project) == previous


