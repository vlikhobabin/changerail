def test_cli_fence_precedes_redirect_to_old_snapshot_after_launcher_crash(
    full_release, tmp_path, monkeypatch
):
    import subprocess
    import os

    project, engine, _ = full_release
    old_source = tmp_path / "old-source"
    git(engine, "clone", "--no-hardlinks", str(engine), str(old_source))
    git(old_source, "config", "user.name", "Fixture")
    git(old_source, "config", "user.email", "fixture@example.invalid")
    # A sealed pre-feature snapshot intentionally has no pending-binding guard.
    put(
        old_source,
        "scripts/changerail/engine_runtime.py",
        "print('OLD_SNAPSHOT_EXECUTED')\n",
    )
    put(old_source, "bin/chrl", "#!/bin/sh\necho OLD_SNAPSHOT_EXECUTED\n", 0o755)
    git(old_source, "add", "scripts/changerail/engine_runtime.py", "bin/chrl")
    git(old_source, "commit", "-qm", "isolated pre-feature engine")
    sealed = tmp_path / "old-snapshot"
    snapshot.create_snapshot(old_source, sealed)
    previous = snapshot.bind_engine(project, sealed)
    before = (project / release.BINDING).read_bytes()
    proposal = binding.prepare(
        project, engine, previous_identity=previous["engine_identity"]
    )
    replace = binding._replace

    def crash(project, name, state):
        replace(project, name, state)
        if name == ".changerail/openspec":
            raise OSError("crash before final binding")

    monkeypatch.setattr(binding, "_replace", crash)
    with pytest.raises(OSError, match="crash before final binding"):
        binding.apply(Path(proposal["proposal"]))
    assert (project / release.BINDING).read_bytes() == before
    for argv in (
        [str(project / ".changerail/chrl"), "--engine-root"],
        [str(project / ".changerail/openspec"), "--version"],
        [str(engine / "bin/chrl"), "--project", str(project), "--engine-root"],
        [str(engine / "bin/openspec"), "--project", str(project), "--version"],
    ):
        result = subprocess.run(argv, capture_output=True, text=True, timeout=5)
        assert result.returncode != 0, argv
        assert "pending executor binding" in result.stderr
        assert "OLD_SNAPSHOT_EXECUTED" not in result.stdout
    direct = subprocess.run(
        [
            "/usr/bin/python3",
            "-B",
            "-P",
            "-m",
            "scripts.changerail.engine_runtime",
            "--engine-root",
        ],
        env={
            **os.environ,
            "PYTHONPATH": str(engine),
            "CHRL_PROJECT_ROOT": str(project),
        },
        cwd=project,
        capture_output=True,
        text=True,
        timeout=5,
    )
    assert direct.returncode != 0
    assert "pending executor binding" in direct.stderr
    monkeypatch.setattr(binding, "_replace", replace)
    binding.apply(Path(proposal["proposal"]), reconcile=True)
    result = subprocess.run(
        [str(project / ".changerail/chrl"), "--engine-root"],
        capture_output=True,
        text=True,
        timeout=10,
    )
    assert result.returncode == 0, result.stderr
    assert result.stdout.strip() == str(engine)
    # Restoring the old file is never the reverse transition API.
    assert snapshot.verify_snapshot(sealed)


def test_applied_binding_retry_allows_new_history_without_rewriting_it(full_release):
    project, engine, _ = full_release
    old = put(project, ".runtime/changerail/runs/old/run.json", '{"reviews_used":2}\n')
    prepared = binding.prepare(project, engine)
    proposal = Path(prepared["proposal"])
    first = binding.apply(proposal)
    new = put(
        project,
        ".runtime/changerail/runs/new/run.json",
        '{"finished_at":"2026-09-12T00:00:00Z","reviews_used":1}\n',
    )
    before = {path: path.read_bytes() for path in (old, new, project / release.BINDING)}
    assert binding.apply(proposal) == first
    assert all(path.read_bytes() == data for path, data in before.items())
    old.write_text('{"reviews_used":0}')
    with pytest.raises(ValueError, match="original retained history"):
        binding.apply(proposal)


